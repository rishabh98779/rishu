def get(doi):
    url = "https://api.crossref.org/works/" + urllib.parse.quote(doi)
    req = urllib.request.Request(url, headers={"User-Agent":"personality-report/1.0 (mailto:research@example.org)"})
    try:
        with urllib.request.urlopen(req, timeout=25) as r:
            m = json.load(r)["message"]
        au = m.get("author", [])
        names = "; ".join(f"{a.get('family','')} {a.get('given','')[:1]}." for a in au[:4])
        yr = (m.get("issued",{}).get("date-parts",[[None]])[0][0])
        return {"doi":doi,"ok":True,"title":(m.get("title") or [""])[0],"container":(m.get("container-title") or [""])[0],
                "volume":m.get("volume"),"issue":m.get("issue"),"page":m.get("page"),"year":yr,"authors":names,
                "type":m.get("type")}
    except Exception as e:
        return {"doi":doi,"ok":False,"err":str(e)}

